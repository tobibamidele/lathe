package importer

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"strconv"
	"strings"

	"github.com/tobibamidele/lathe/schema"
)

// RenderConfig controls the Go schema file emitted from a snapshot.
type RenderConfig struct {
	Package    string
	Output     string
	Migrations string
	Source     string // human-readable origin, e.g. "migrations"
}

// Render writes a schema package in lathe's builder syntax.
func Render(snap *schema.Snapshot, cfg RenderConfig) ([]byte, error) {
	if cfg.Package == "" {
		cfg.Package = "schema"
	}
	if cfg.Output == "" {
		cfg.Output = "db"
	}
	if cfg.Migrations == "" {
		cfg.Migrations = "migrations"
	}
	dialect, err := dialectName(snap.Dialect)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by `lathe import` from SQL migrations. Review it before committing.\n")
	if cfg.Source != "" {
		b.WriteString("//\n// Source: " + cfg.Source + "\n")
	}
	fmt.Fprintf(&b, "package %s\n\n", cfg.Package)
	b.WriteString("import s \"github.com/tobibamidele/lathe/schema\"\n\n")
	b.WriteString("// Schema is the entry point lathe looks for.\n")
	b.WriteString("var Schema = s.New(s.Config{\n")
	fmt.Fprintf(&b, "\tDialect:    s.%s,\n", dialect)
	fmt.Fprintf(&b, "\tOutput:     %s,\n", strconv.Quote(cfg.Output))
	fmt.Fprintf(&b, "\tMigrations: %s,\n", strconv.Quote(cfg.Migrations))
	b.WriteString("},\n")
	for _, t := range snap.Tables {
		writeTable(&b, t)
	}
	b.WriteString(")\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated schema: %w\n%s", err, b.String())
	}
	return src, nil
}

func dialectName(d schema.Dialect) (string, error) {
	switch d {
	case schema.Postgres:
		return "Postgres", nil
	case schema.MySQL:
		return "MySQL", nil
	case schema.SQLite:
		return "SQLite", nil
	}
	return "", fmt.Errorf("unsupported dialect %q", d)
}

func writeTable(b *bytes.Buffer, t *schema.TableDef) {
	fmt.Fprintf(b, "\ts.Table(%s,\n", strconv.Quote(t.Name))
	for _, c := range t.Columns {
		fmt.Fprintf(b, "\t\t%s,\n", columnExpr(t, c))
	}
	if len(t.PrimaryKey) > 1 {
		fmt.Fprintf(b, "\t\ts.PrimaryKey(%s),\n", quotedList(t.PrimaryKey))
	}
	for _, ix := range t.Indexes {
		fmt.Fprintf(b, "\t\t%s,\n", indexExpr(t, ix))
	}
	for _, fk := range t.ForeignKeys {
		fmt.Fprintf(b, "\t\t%s,\n", foreignKeyExpr(t, fk))
	}
	b.WriteString("\t)")
	if t.Model != "" {
		fmt.Fprintf(b, ".Model(%s)", strconv.Quote(t.Model))
	}
	b.WriteString(",\n")
}

func columnExpr(t *schema.TableDef, c *schema.ColumnDef) string {
	var b strings.Builder
	b.WriteString("s.")
	b.WriteString(typeExpr(c.Type))
	b.WriteString("(")
	b.WriteString(strconv.Quote(c.Name))
	if c.Type.Kind == schema.KindVarChar {
		fmt.Fprintf(&b, ", %d", c.Type.Length)
	}
	if c.Type.Kind == schema.KindDecimal {
		fmt.Fprintf(&b, ", %d, %d", c.Type.Precision, c.Type.Scale)
	}
	if c.Type.Kind == schema.KindEnum {
		for _, v := range c.Type.Values {
			b.WriteString(", " + strconv.Quote(v))
		}
	}
	b.WriteString(")")
	if len(t.PrimaryKey) == 1 && t.PrimaryKey[0] == c.Name {
		b.WriteString(".PrimaryKey()")
	}
	if c.AutoIncrement {
		b.WriteString(".AutoIncrement()")
	}
	if c.Nullable && !c.AutoIncrement {
		b.WriteString(".Nullable()")
	}
	if c.Default != nil {
		b.WriteString(goDefaultExpr(c.Default))
	}
	return b.String()
}

func typeExpr(t schema.Type) string {
	switch t.Kind {
	case schema.KindSmallInt:
		return "SmallInt"
	case schema.KindInt:
		return "Int"
	case schema.KindBigInt:
		return "BigInt"
	case schema.KindReal:
		return "Real"
	case schema.KindDouble:
		return "Double"
	case schema.KindDecimal:
		return "Decimal"
	case schema.KindBool:
		return "Bool"
	case schema.KindVarChar:
		return "VarChar"
	case schema.KindText:
		return "Text"
	case schema.KindUUID:
		return "UUID"
	case schema.KindTimestamp:
		return "Timestamp"
	case schema.KindDate:
		return "Date"
	case schema.KindJSON:
		return "JSON"
	case schema.KindBytes:
		return "Bytes"
	case schema.KindEnum:
		return "Enum"
	}
	return "Text"
}

func goDefaultExpr(d *schema.Default) string {
	switch d.Kind {
	case schema.DefaultNow:
		return ".DefaultNow()"
	case schema.DefaultUUID:
		return ".DefaultUUID()"
	case schema.DefaultExpr:
		return ".DefaultExpr(" + strconv.Quote(d.Value) + ")"
	case schema.DefaultLiteral:
		switch d.Lit {
		case schema.LitBool:
			return ".Default(" + d.Value + ")"
		case schema.LitNumber:
			if validNumber(d.Value) {
				return ".Default(" + d.Value + ")"
			}
			return ".DefaultExpr(" + strconv.Quote(d.Value) + ")"
		default:
			return ".Default(" + strconv.Quote(d.Value) + ")"
		}
	}
	return ""
}

func indexExpr(t *schema.TableDef, ix *schema.IndexDef) string {
	builder := "s.Index"
	prefix := "idx"
	if ix.Unique {
		builder = "s.UniqueIndex"
		prefix = "uq"
	}
	var b strings.Builder
	b.WriteString(builder)
	b.WriteString("(")
	b.WriteString(quotedList(ix.Columns))
	b.WriteString(")")
	if ix.Name != schema.AutoName(prefix, t.Name, ix.Columns...) {
		b.WriteString(".Name(" + strconv.Quote(ix.Name) + ")")
	}
	return b.String()
}

func foreignKeyExpr(t *schema.TableDef, fk *schema.ForeignKeyDef) string {
	var b strings.Builder
	b.WriteString("s.ForeignKey(")
	b.WriteString(quotedList(fk.Columns))
	b.WriteString(").References(")
	b.WriteString(strconv.Quote(fk.RefTable))
	for _, c := range fk.RefColumns {
		b.WriteString(", " + strconv.Quote(c))
	}
	b.WriteString(")")
	if fk.OnDelete != schema.NoAction {
		b.WriteString(".OnDelete(s." + actionName(fk.OnDelete) + ")")
	}
	if fk.OnUpdate != schema.NoAction {
		b.WriteString(".OnUpdate(s." + actionName(fk.OnUpdate) + ")")
	}
	if fk.Name != schema.AutoName("fk", t.Name, fk.Columns...) {
		b.WriteString(".Name(" + strconv.Quote(fk.Name) + ")")
	}
	return b.String()
}

func actionName(a schema.Action) string {
	switch a {
	case schema.Cascade:
		return "Cascade"
	case schema.Restrict:
		return "Restrict"
	case schema.SetNull:
		return "SetNull"
	case schema.SetDefault:
		return "SetDefault"
	}
	return "NoAction"
}

func quotedList(values []string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = strconv.Quote(v)
	}
	return strings.Join(parts, ", ")
}

var safeNumber = regexp.MustCompile(`^-?[0-9]+(\.[0-9]+)?$`)

// validNumber reports whether a raw numeric default can be emitted as a Go
// literal and read back by schema's validator.
func validNumber(s string) bool { return safeNumber.MatchString(s) }
