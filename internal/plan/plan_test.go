func TestRenames(t *testing.T) {
	old := snap(t, s.Postgres,
		s.Table("accounts", s.Int("id").PrimaryKey(), s.Text("name")),
		s.Table("notes", s.Int("id").PrimaryKey(), s.Int("account_id").References("accounts", "id")),
	)
	cur := snap(t, s.Postgres,
		s.Table("users", s.Int("id").PrimaryKey(), s.Text("full_name").RenamedFrom("name")).RenamedFrom("accounts"),
		s.Table("notes", s.Int("id").PrimaryKey(), s.Int("account_id").References("users", "id")),
	)
	p, d := diff(t, old, cur)
	got := up(t, p, d)
	mustContain(t, got, `ALTER TABLE "accounts" RENAME TO "users"`, `ALTER TABLE "users" RENAME COLUMN "name" TO "full_name"`)
	mustNotContain(t, got, "DROP TABLE", "DROP COLUMN", "CREATE TABLE")
	// the FK in notes only changed because its target was renamed: no churn
	mustNotContain(t, got, "FOREIGN KEY", "DROP CONSTRAINT")
	dn := down(t, p, d)
	mustContain(t, dn, `RENAME COLUMN "full_name" TO "name"`, `ALTER TABLE "users" RENAME TO "accounts"`)
}

