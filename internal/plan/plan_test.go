func TestIndexAndForeignKeyChanges(t *testing.T) {
	old := snap(t, s.Postgres,
		s.Table("u", s.Int("id").PrimaryKey()),
		s.Table("t", s.Int("id").PrimaryKey(), s.Int("u_id").References("u", "id"), s.Text("a"), s.Index("a")),
	)
	cur := snap(t, s.Postgres,
		s.Table("u", s.Int("id").PrimaryKey()),
		s.Table("t", s.Int("id").PrimaryKey(), s.Int("u_id").References("u", "id").OnDelete(s.Cascade), s.Text("a"), s.UniqueIndex("a")),
	)
	p, d := diff(t, old, cur)
	got := up(t, p, d)
	mustContain(t, got, `DROP INDEX "idx_t_a"`, `CREATE UNIQUE INDEX "uq_t_a"`,
		`DROP CONSTRAINT "fk_t_u_id"`, `ADD CONSTRAINT "fk_t_u_id" FOREIGN KEY ("u_id") REFERENCES "u" ("id") ON DELETE CASCADE`)
	if strings.Index(got, "DROP CONSTRAINT") > strings.Index(got, "ADD CONSTRAINT") {
		t.Error("constraint must be dropped before it is re-added")
	}
}

func TestDropTableOrdersDependentsFirst(t *testing.T) {
	old := snap(t, s.MySQL, users(), posts())
	cur := snap(t, s.MySQL)
	p, d := diff(t, old, cur)
	got := up(t, p, d)
	if strings.Index(got, "DROP TABLE `posts`") > strings.Index(got, "DROP TABLE `users`") {
		t.Errorf("posts references users, so it must be dropped first:\n%s", got)
	}
	if len(p.Warnings()) != 2 {
		t.Errorf("want a warning per dropped table, got %v", p.Warnings())
	}
}

