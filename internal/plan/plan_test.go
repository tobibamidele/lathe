func snap(t *testing.T, d s.Dialect, tables ...*s.TableBuilder) *s.Snapshot {
	t.Helper()
	exp, err := s.New(s.Config{Dialect: d}, tables...).Export()
	if err != nil {
		t.Fatal(err)
	}
	return exp.Snapshot
}

func diff(t *testing.T, old, cur *s.Snapshot) (*plan.Plan, ddl.Dialect) {
	t.Helper()
	d, err := ddl.For(cur.Dialect)
	if err != nil {
		t.Fatal(err)
	}
	p, err := plan.Diff(old, cur, d)
	if err != nil {
		t.Fatal(err)
	}
	return p, d
}

func up(t *testing.T, p *plan.Plan, d ddl.Dialect) string {
	t.Helper()
	stmts, err := p.Up(d)
	if err != nil {
		t.Fatal(err)
	}
	return strings.Join(stmts, ";\n")
}

func down(t *testing.T, p *plan.Plan, d ddl.Dialect) string {
	t.Helper()
	stmts, err := p.Down(d)
	if err != nil {
		t.Fatal(err)
	}
	return strings.Join(stmts, ";\n")
}

func mustContain(t *testing.T, got string, want ...string) {
	t.Helper()
	for _, w := range want {
		if !strings.Contains(got, w) {
			t.Errorf("missing %q in:\n%s", w, got)
		}
	}
}

func mustNotContain(t *testing.T, got string, bad ...string) {
	t.Helper()
	for _, w := range bad {
		if strings.Contains(got, w) {
			t.Errorf("unexpected %q in:\n%s", w, got)
		}
	}
}

func users() *s.TableBuilder {
	return s.Table("users",
		s.BigInt("id").PrimaryKey().AutoIncrement(),
		s.VarChar("email", 255).Unique(),
		s.Enum("role", "admin", "member").Default("member"),
		s.Money("balance").Default("0"),
		s.Timestamp("created_at").DefaultNow(),
	)
}

func posts() *s.TableBuilder {
	return s.Table("posts",
		s.UUID("id").PrimaryKey().DefaultUUID(),
		s.BigInt("author_id").References("users", "id").OnDelete(s.Cascade).Index(),
		s.Text("body").Nullable(),
	)
}

func TestCreateEachDialect(t *testing.T) {
	cases := map[s.Dialect][]string{
		s.Postgres: {
			`"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL`,
			`"role" TEXT NOT NULL DEFAULT 'member' CONSTRAINT "ck_users_role" CHECK ("role" IN ('admin', 'member'))`,
			`"balance" NUMERIC(19, 4) NOT NULL DEFAULT 0`,
			`"created_at" TIMESTAMPTZ NOT NULL DEFAULT now()`,
			`"id" UUID NOT NULL DEFAULT gen_random_uuid()`,
			`CONSTRAINT "fk_posts_author_id" FOREIGN KEY ("author_id") REFERENCES "users" ("id") ON DELETE CASCADE`,
			`CREATE UNIQUE INDEX "uq_users_email" ON "users" ("email")`,
		},
		s.MySQL: {
			"`id` BIGINT NOT NULL AUTO_INCREMENT",
			"`role` ENUM('admin', 'member') NOT NULL DEFAULT 'member'",
			"`created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)",
			"`id` CHAR(36) NOT NULL DEFAULT (UUID())",
			"`body` TEXT NULL",
			"CREATE INDEX `idx_posts_author_id` ON `posts` (`author_id`)",
		},
		s.SQLite: {
			`"id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL`,
			`"balance" DECIMAL(19, 4) NOT NULL DEFAULT 0`,
			`"created_at" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP`,
			`CONSTRAINT "ck_users_role" CHECK ("role" IN ('admin', 'member'))`,
			`"body" TEXT`,
		},
	}
	for dialect, wants := range cases {
		t.Run(string(dialect), func(t *testing.T) {
			p, d := diff(t, nil, snap(t, dialect, users(), posts()))
			got := up(t, p, d)
			mustContain(t, got, wants...)
			// users must be created before posts everywhere (FK target first)
			if strings.Index(got, "CREATE TABLE "+d.Quote("users")) > strings.Index(got, "CREATE TABLE "+d.Quote("posts")) {
				t.Errorf("users must be created before posts:\n%s", got)
			}
			dn := down(t, p, d)
			if strings.Index(dn, "DROP TABLE "+d.Quote("posts")) > strings.Index(dn, "DROP TABLE "+d.Quote("users")) {
				t.Errorf("posts must be dropped before users:\n%s", dn)
			}
		})
	}
}

func TestNoChanges(t *testing.T) {
	a := snap(t, s.Postgres, users(), posts())
	b := snap(t, s.Postgres, users(), posts())
	if p, _ := diff(t, a, b); !p.Empty() {
		t.Errorf("identical snapshots should not produce a plan: %v", p.Describe())
	}
}

func TestDialectChangeRejected(t *testing.T) {
	d, _ := ddl.For(s.MySQL)
	_, err := plan.Diff(snap(t, s.Postgres, users()), snap(t, s.MySQL, users()), d)
	if err == nil || !strings.Contains(err.Error(), "dialect changed") {
		t.Fatalf("want dialect error, got %v", err)
	}
}

func TestCircularForeignKeys(t *testing.T) {
	a := s.Table("a", s.Int("id").PrimaryKey(), s.Int("b_id").Nullable().References("b", "id"))
	b := s.Table("b", s.Int("id").PrimaryKey(), s.Int("a_id").Nullable().References("a", "id"))
	for _, dialect := range []s.Dialect{s.Postgres, s.MySQL} {
		t.Run(string(dialect), func(t *testing.T) {
			p, d := diff(t, nil, snap(t, dialect, a, b))
			got := up(t, p, d)
			// exactly one FK is deferred to an ALTER TABLE, after both tables exist
			if n := strings.Count(got, "ADD CONSTRAINT"); n != 1 {
				t.Errorf("want 1 deferred foreign key, got %d:\n%s", n, got)
			}
			if strings.Index(got, "ADD CONSTRAINT") < strings.LastIndex(got, "CREATE TABLE") {
				t.Errorf("deferred FK must come after all CREATE TABLEs:\n%s", got)
			}
			dn := down(t, p, d)
			if !strings.HasPrefix(dn, "ALTER TABLE") {
				t.Errorf("down must drop the deferred FK first:\n%s", dn)
			}
		})
	}
	// SQLite resolves references lazily, so everything stays inline.
	p, d := diff(t, nil, snap(t, s.SQLite, a, b))
	mustNotContain(t, up(t, p, d), "ADD CONSTRAINT")
}

func TestAddAndDropColumn(t *testing.T) {
	old := snap(t, s.Postgres, s.Table("t", s.Int("id").PrimaryKey(), s.Text("gone")))
	cur := snap(t, s.Postgres, s.Table("t", s.Int("id").PrimaryKey(), s.Text("bio").Nullable()))
	p, d := diff(t, old, cur)
	mustContain(t, up(t, p, d), `ALTER TABLE "t" DROP COLUMN "gone"`, `ALTER TABLE "t" ADD COLUMN "bio" TEXT`)
	mustContain(t, down(t, p, d), `ALTER TABLE "t" DROP COLUMN "bio"`, `ALTER TABLE "t" ADD COLUMN "gone" TEXT NOT NULL`)
	if w := p.Warnings(); len(w) != 1 || !strings.Contains(w[0], "drops column t.gone") {
		t.Errorf("want data loss warning, got %v", w)
	}
}

func TestAlterColumnPostgres(t *testing.T) {
	old := snap(t, s.Postgres, s.Table("t",
		s.Int("id").PrimaryKey(),
		s.VarChar("name", 50).Default("x"),
		s.Text("note").Nullable(),
		s.Enum("kind", "a", "b"),
	))
	cur := snap(t, s.Postgres, s.Table("t",
		s.Int("id").PrimaryKey(),
		s.VarChar("name", 100).Default("y"),
		s.Text("note"),
		s.Enum("kind", "a", "b", "c"),
	))
	p, d := diff(t, old, cur)
	got := up(t, p, d)
	mustContain(t, got,
		`ALTER COLUMN "name" DROP DEFAULT`,
		`ALTER COLUMN "name" TYPE VARCHAR(100) USING "name"::VARCHAR(100)`,
		`ALTER COLUMN "name" SET DEFAULT 'y'`,
		`ALTER COLUMN "note" SET NOT NULL`,
		`DROP CONSTRAINT "ck_t_kind"`,
		`ADD CONSTRAINT "ck_t_kind" CHECK ("kind" IN ('a', 'b', 'c'))`,
	)
	if len(p.Warnings()) == 0 {
		t.Error("type change should warn")
	}
	mustContain(t, down(t, p, d), `ALTER COLUMN "note" DROP NOT NULL`, `TYPE VARCHAR(50)`)
}

