func TestSQLiteRebuild(t *testing.T) {
	old := snap(t, s.SQLite,
		s.Table("u", s.Int("id").PrimaryKey()),
		s.Table("t", s.Int("id").PrimaryKey(), s.Int("u_id").Nullable(), s.Text("n").Nullable(), s.Index("u_id")),
	)
	cur := snap(t, s.SQLite,
		s.Table("u", s.Int("id").PrimaryKey()),
		s.Table("t", s.Int("id").PrimaryKey(), s.Int("u_id").Nullable().References("u", "id"), s.Text("n").Default("z"), s.Index("u_id"), s.Text("extra").Nullable()),
	)
	p, d := diff(t, old, cur)
	got := up(t, p, d)
	mustContain(t, got,
		`CREATE TABLE "__lathe_new_t"`,
		`CONSTRAINT "fk_t_u_id" FOREIGN KEY ("u_id") REFERENCES "u" ("id")`,
		// rows are copied, and NULLs are replaced by the new default
		`INSERT INTO "__lathe_new_t" ("id", "u_id", "n") SELECT "id", "u_id", COALESCE("n", 'z') FROM "t"`,
		`DROP TABLE "t"`,
		`ALTER TABLE "__lathe_new_t" RENAME TO "t"`,
		`CREATE INDEX "idx_t_u_id" ON "t" ("u_id")`,
	)
	// the inverse rebuild restores the old shape
	dn := down(t, p, d)
	mustContain(t, dn, `CREATE TABLE "__lathe_new_t"`)
	mustNotContain(t, dn, "FOREIGN KEY", `"extra"`)
}

